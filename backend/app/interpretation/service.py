class InterpretationBusyError(RuntimeError):
    """The same cache key is already being generated by another request."""


def _sha256_json(value: Any) -> str:
    return hashlib.sha256(
        json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def cache_key(bundle: dict[str, Any]) -> str:
    """Cache identity is bound to project, drug, build, evidence semantics, prompt, and model."""
    return _sha256_json(
        {
            "project_id": bundle.get("project_id"),
            "drug_id": (bundle.get("candidate") or {}).get("drug_id"),
            "graph_build_id": bundle.get("graph_build_id"),
            "top10_sha256": bundle.get("top10_sha256"),
            "s1_sha256": bundle.get("s1_sha256"),
            "prompt_version": prompt_module.PROMPT_VERSION,
            "prompt_sha256": prompt_module.prompt_fingerprint(),
            "model": settings.deepseek_model,
            "semantic_evidence_sha256": evidence_module.semantic_evidence_sha256(bundle),
        }
    )


def _page_graph_build_id() -> str | None:
    try:
        data = json.loads(PAGE_RESULTS_PATH.read_text(encoding="utf-8"))
        value = data.get("graph_build_id")
        return value if isinstance(value, str) else None
    except (OSError, json.JSONDecodeError):
        return None


def _minimal_evidence(bundle: dict[str, Any]) -> bool:
    counts = bundle.get("counts") or {}
    return bool(
        counts.get("s2_conditions")
        or counts.get("direct_target_paths")
        or counts.get("public_pathway_paths")
        or counts.get("s1_enrichment_paths")
        or counts.get("s1_deg_paths")
    )


def _gap_text(gap: str) -> str:
    return GAP_LABELS.get(gap, gap)


def _deterministic_explanation(bundle: dict[str, Any]) -> dict[str, Any]:
    return {
        "screening_rationale": [],
        "target_mechanism": [],
        "pathway_association": [],
        "er_positive_relevance": [],
        "mechanism_hypotheses": [],
    }


def _backend_limitations(bundle: dict[str, Any]) -> list[str]:
    """Safe, deterministic limitations derived from data coverage, not model text."""
    counts = bundle.get("counts") or {}
    candidate = bundle.get("candidate") or {}
    grade = bundle.get("grade_matrix") or {}
    items = ["结果只基于当前项目的 S1/S2 计算和知识图谱证据，尚未经过实验验证。"]
    if (candidate.get("n_signatures") or 0) <= 1:
        items.append("每个纳入条件只有一个共识签名，剂量稳定性不能替代独立实验重复。")
    if counts.get("direct_target_paths", 0) == 0:
        items.append("当前图谱没有可追溯的药物—靶点断言，无法支持靶点机制解释。")
    elif any(target.get("s1_deg") is None for target in (bundle.get("targets") or [])):
        items.append("部分靶点没有在本项目 S1 差异表达中验证，靶点注释不等于疾病表达证据。")
    if counts.get("s1_enrichment_paths", 0) == 0:
        items.append("当前没有靶点与 S1 富集通路的交汇证据。")
    else:
        items.append("靶点—通路关联只是间接线索，不代表因果关系。")
    if grade.get("expression_reversal_grade"):
        items.append(f"原始表达逆转等级：{grade['expression_reversal_grade']}。")
    if grade.get("known_target_grade"):
        items.append(f"原始靶点等级：{grade['known_target_grade']}。")
    if grade.get("mechanism_hypothesis_status"):
        items.append(f"原始机制假设状态：{grade['mechanism_hypothesis_status']}。")
    return items[:6]


def _backend_validation_suggestions(bundle: dict[str, Any]) -> list[str]:
    counts = bundle.get("counts") or {}
    suggestions = []
    if not (bundle.get("compound") or {}).get("mapped"):
        suggestions.append("先完成化合物结构身份核验并纳入当前图谱，再评估机制关联。")
    if counts.get("direct_target_paths", 0) and counts.get("s1_enrichment_paths", 0):
        suggestions.append("在 ER+ 乳腺癌细胞模型中验证靶点结合、通路扰动与剂量反应。")
    else:
        suggestions.append("补充可追溯的靶点或通路证据后重新生成解释。")
    suggestions.append("用独立数据集复现表达逆转结果，并与 PRISM 等敏感性数据交叉核对。")
    suggestions.append("将当前结果视为待验证计算候选，不作为用药或临床决策依据。")
    return suggestions[:4]


def _backend_insufficient_evidence(bundle: dict[str, Any]) -> list[dict[str, Any]]:
    return [
        {"text": _gap_text(gap), "relation": "unknown", "layer": "D", "evidence_ids": [], "path_ids": []}
        for gap in (bundle.get("evidence_gaps") or [])
    ]


def _summary(bundle: dict[str, Any], layer_counts: dict[str, int]) -> dict[str, Any]:
    counts = bundle.get("counts") or {}
    targets = bundle.get("targets") or []
    pathways = bundle.get("pathways") or []
    return {
        "graph_build_id": bundle.get("graph_build_id"),
        "mapped": bool((bundle.get("compound") or {}).get("mapped")),
        "compound_id": (bundle.get("compound") or {}).get("compound_id"),
        "target_count": len(targets),
        "s1_target_count": sum(1 for target in targets if target.get("s1_deg")),
        "pathway_count": len({item.get("pathway_id") for item in pathways if item.get("pathway_id")}),
        "s2_condition_count": counts.get("s2_conditions", 0),
        "unique_evidence_count": counts.get("unique_evidence", 0),
        "verified_reference_count": counts.get("verified_references", 0),
        "evidence_gap_count": len(bundle.get("evidence_gaps") or []),
        "layer_counts": layer_counts,
        "top10_sha256": bundle.get("top10_sha256"),
        "s1_sha256": bundle.get("s1_sha256"),
        "prompt_sha256": prompt_module.prompt_fingerprint(),
    }


def _section_status(bundle: dict[str, Any], explanation: dict[str, Any]) -> dict[str, str]:
    """Per-section availability, so the UI can show 'no evidence' instead of a blank card."""
    counts = bundle.get("counts") or {}
    availability = {
        "screening_rationale": "available" if counts.get("s2_conditions") else "no_screening_evidence",
        "target_mechanism": "available" if counts.get("direct_target_paths") else "no_target_evidence",
        "pathway_association": "available" if counts.get("s1_enrichment_paths") or counts.get("public_pathway_paths") else "no_pathway_evidence",
        "er_positive_relevance": "available"
        if counts.get("s2_conditions") or counts.get("s1_deg_paths") or counts.get("s1_enrichment_paths") or counts.get("public_pathway_paths")
        else "no_er_context_evidence",
        "mechanism_hypotheses": "available" if counts.get("direct_target_paths") or counts.get("s1_enrichment_paths") else "no_hypothesis_basis",
    }
    for section, status in availability.items():
        if status == "available" and not (explanation.get(section) or []):
            availability[section] = "available_but_no_valid_claims"
    return availability


def _assemble(
    bundle: dict[str, Any],
    explanation: dict[str, Any],
    issues: list[dict[str, Any]],
    audit: dict[str, Any],
    *,
    metadata: dict[str, Any],
    status: str,
    cache_key_value: str,
) -> dict[str, Any]:
    coverage = validator.backend_coverage(bundle)
    page_build = _page_graph_build_id()
    candidate = bundle.get("candidate") or {}
    model_name = metadata.get("model") or "deterministic-rule"
    limitations = _backend_limitations(bundle)
    suggestions = _backend_validation_suggestions(bundle)
    insufficient = _backend_insufficient_evidence(bundle)
    audit["layer_counts"]["D"] = len(insufficient)
    return {
        "status": status,
        "mode": "deepseek_flash" if metadata.get("model") else "deterministic_rule",
        "project_id": bundle.get("project_id"),
        "graph_build_id": bundle.get("graph_build_id"),
        "drug_id": candidate.get("drug_id"),
        "drug_name": candidate.get("drug_name"),
        "rank": candidate.get("rank"),
        "rank_source": "experiments/final_results/results/final_top10.csv（冻结，SHA-256 已核验）",
        "screening": {
            "score_name": candidate.get("score_name"),
            "score_value": candidate.get("score_value"),
            "n_signatures": candidate.get("n_signatures"),
            "n_dose_conditions": candidate.get("n_dose_conditions"),
            "negative_dose_fraction": candidate.get("negative_dose_fraction"),
            "primary_dose": candidate.get("primary_dose"),
            "cell_id": candidate.get("cell_id"),
            "pert_time": candidate.get("pert_time"),
        },
        "model_name": model_name,
        "prompt_version": prompt_module.PROMPT_VERSION,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "cached": False,
        "cache_key": cache_key_value,
        "latency_seconds": metadata.get("latency_seconds"),
        "usage": metadata.get("usage") or {},
        "finish_reason": metadata.get("finish_reason"),
        "evidence_input_sha256": bundle.get("evidence_input_sha256"),
        "top10_sha256": bundle.get("top10_sha256"),
        "evidence_summary": _summary(bundle, audit.get("layer_counts") or {}),
        "screening_rationale": explanation.get("screening_rationale", []),
        "target_mechanism": explanation.get("target_mechanism", []),
        "pathway_association": explanation.get("pathway_association", []),
        "er_positive_relevance": explanation.get("er_positive_relevance", []),
        "mechanism_hypotheses": explanation.get("mechanism_hypotheses", []),
        "section_status": _section_status(bundle, explanation),
        "evidence_assessment": {
            **coverage,
            "grade_matrix": bundle.get("grade_matrix"),
            "model_verdict_ignored": audit.get("model_verdict"),
        },
        "limitations": limitations,
        "validation_suggestions": suggestions,
        "insufficient_evidence": insufficient,
        "evidence_references": bundle.get("evidence_references", []),
        "claim_audit": {
            "dropped_claims": audit.get("dropped_claims", 0),
            "downgraded_claims": audit.get("downgraded_claims", 0),
            "accepted_claims": audit.get("accepted_claims", 0),
            "issue_count": len(issues),
            "issues": issues,
            "ignored_model_free_text": audit.get("ignored_free_text", []),
            "model_verdict_ignored": audit.get("model_verdict"),
        },
        "graph_build_matches_page": bool(page_build and page_build == bundle.get("graph_build_id")),
        "page_graph_build_id": page_build,
        "page_version_note": (
            "排名来自冻结 Top10 文件；机制证据来自当前 GraphBuild。"
            + ("两者版本一致。" if page_build and page_build == bundle.get("graph_build_id") else "页面历史证据版本与当前机制证据版本不同，数量差异属正常版本差异。")
        ),
        "disclaimer": "本解释仅用于科研辅助，不构成临床用药建议。",
    }


def _read_cache(path: Path) -> dict[str, Any] | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return data if isinstance(data, dict) else None


def _write_cache(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(f".{uuid4().hex}.tmp")
    temp.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    temp.replace(path)


def _lock_for(key: str) -> threading.Lock:
    with _LOCKS_GUARD:
        return _LOCKS.setdefault(key, threading.Lock())


def interpret_drug(
    db,
    project_id: str,
    drug_id: str,
    graph_build_id: str | None = None,
    *,
    force_regenerate: bool = False,
) -> dict[str, Any]:
    bundle = evidence_module.collect_evidence(db, project_id, drug_id, graph_build_id)
    key = cache_key(bundle)
    cache_path = CACHE_DIR / f"{key}.json"

    if not force_regenerate:
        cached = _read_cache(cache_path)
        if cached is not None:
            cached["cached"] = True
            cached["cache_key"] = key
            return cached

    lock = _lock_for(key)
    if not lock.acquire(blocking=False):
        raise InterpretationBusyError("该药物解释正在生成中，请稍后重试")
    try:
        if not force_regenerate:
            cached = _read_cache(cache_path)
            if cached is not None:
                cached["cached"] = True
                cached["cache_key"] = key
                return cached

        if _minimal_evidence(bundle):
            raw, metadata = provider.chat_json(prompt_module.build_messages(bundle))
            clean, issues, audit = validator.validate_explanation(raw, bundle)
            status = "generated"
        else:
            raw = _deterministic_explanation(bundle)
            clean, issues, audit = validator.validate_explanation(raw, bundle)
            metadata = {"model": None, "latency_seconds": 0.0, "usage": {}}
            status = "coverage_insufficient"

        result = _assemble(bundle, clean, issues, audit, metadata=metadata, status=status, cache_key_value=key)
        _write_cache(cache_path, result)
        return result
    finally:
        lock.release()
